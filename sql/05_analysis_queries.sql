**Query #9**

    SELECT
        py.payer_name,
    
        COUNT(c.claim_id) AS total_claims,
    
        SUM(
            CASE
                WHEN c.claim_status = 'Denied'
                THEN 1
                ELSE 0
            END
        ) AS denied_claims,
    
        ROUND(
            100.0 *
            SUM(
                CASE
                    WHEN c.claim_status = 'Denied'
                    THEN 1
                    ELSE 0
                END
            )
            / COUNT(c.claim_id),
            2
        ) AS denial_rate_percent
    
    FROM claims c
    
    JOIN payers py
        ON c.payer_id = py.payer_id
    
    GROUP BY py.payer_name
    ORDER BY denial_rate_percent DESC;

