    SELECT
        c.claim_id,
        c.allowed_amount,
    
        COALESCE(SUM(p.payment_amount), 0) AS total_paid,
        COALESCE(SUM(p.adjustment_amount), 0) AS total_adjustment,
        COALESCE(SUM(p.patient_responsibility), 0) AS patient_responsibility,
    
        ROUND(
            c.allowed_amount
            - COALESCE(SUM(p.payment_amount), 0)
            - COALESCE(SUM(p.adjustment_amount), 0)
            - COALESCE(SUM(p.patient_responsibility), 0),
            2
        ) AS outstanding_ar
    
    FROM claims c
    
    LEFT JOIN payments p
        ON c.claim_id = p.claim_id
    
    GROUP BY
        c.claim_id,
        c.allowed_amount
    
    ORDER BY outstanding_ar DESC;

