**Query #40**

    WITH payment_summary AS (
        SELECT
            claim_id,
            SUM(payment_amount) AS total_paid,
            SUM(adjustment_amount) AS total_adjustments,
            SUM(patient_responsibility) AS patient_responsibility
        FROM payments
        GROUP BY claim_id
    ),
    followup_summary AS (
        SELECT
            claim_id,
            COUNT(*) AS followup_count,
            MAX(followup_date) AS last_followup_date
        FROM ar_followups
        GROUP BY claim_id
    ),
    denial_summary AS (
        SELECT
            claim_id,
            COUNT(*) AS denial_count,
            SUM(denial_amount) AS total_denied_amount,
            MAX(denial_date) AS latest_denial_date
        FROM denials
        GROUP BY claim_id
    ),
    claim_risk AS (
        SELECT
            c.claim_id,
            py.payer_name,
            c.claim_status,
            c.submission_date,
    
            DATEDIFF(
                '2026-09-21',
                c.submission_date
            ) AS claim_age_days,
    
            ROUND(
                c.allowed_amount
                - COALESCE(ps.total_paid, 0)
                - COALESCE(ps.total_adjustments, 0)
                - COALESCE(ps.patient_responsibility, 0),
                2
            ) AS outstanding_ar,
    
            COALESCE(fs.followup_count, 0) AS followup_count,
            fs.last_followup_date,
    
            COALESCE(ds.denial_count, 0) AS denial_count,
            COALESCE(ds.total_denied_amount, 0) AS total_denied_amount,
            ds.latest_denial_date
    
        FROM claims c
    
        JOIN payers py
            ON c.payer_id = py.payer_id
    
        LEFT JOIN payment_summary ps
            ON c.claim_id = ps.claim_id
    
        LEFT JOIN followup_summary fs
            ON c.claim_id = fs.claim_id
    
        LEFT JOIN denial_summary ds
            ON c.claim_id = ds.claim_id
    )
    SELECT
        claim_id,
        payer_name,
        claim_status,
        claim_age_days,
        outstanding_ar,
        followup_count,
        last_followup_date,
        denial_count,
        total_denied_amount,
        latest_denial_date,
    
        CASE
            WHEN outstanding_ar <= 0
                THEN 'No Positive AR'
    
            WHEN claim_age_days > 120
                 AND outstanding_ar > 10000
                THEN 'Critical'
    
            WHEN claim_age_days > 90
                 AND outstanding_ar > 5000
                THEN 'High'
    
            WHEN claim_age_days > 60
                 AND outstanding_ar > 2500
                THEN 'Medium'
    
            ELSE 'Routine'
        END AS ar_priority
    
    FROM claim_risk
    
    WHERE outstanding_ar > 0
    
    ORDER BY
        CASE
            WHEN claim_age_days > 120
                 AND outstanding_ar > 10000
                THEN 1
    
            WHEN claim_age_days > 90
                 AND outstanding_ar > 5000
                THEN 2
    
            WHEN claim_age_days > 60
                 AND outstanding_ar > 2500
                THEN 3
    
            ELSE 4
        END,
        outstanding_ar DESC;

