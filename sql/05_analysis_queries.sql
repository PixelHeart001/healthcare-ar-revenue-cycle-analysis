**Query #10**

    SELECT
        SUM(
            c.allowed_amount
            - COALESCE(p.total_paid, 0)
            - COALESCE(p.total_adjustment, 0)
            - COALESCE(p.total_patient_responsibility, 0)
        ) AS total_outstanding_ar
    
    FROM claims c
    
    LEFT JOIN
    (
        SELECT
            claim_id,
            SUM(payment_amount) AS total_paid,
            SUM(adjustment_amount) AS total_adjustment,
            SUM(patient_responsibility) AS total_patient_responsibility
        FROM payments
        GROUP BY claim_id
    ) p
        ON c.claim_id = p.claim_id;

